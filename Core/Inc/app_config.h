/**
  ******************************************************************************
  * @file    app_config.h
  * @brief   全部可调参数集中在这里 —— 调车只改这个文件
  *
  *   三类参数：
  *   1) 机械参数：卷尺/卡尺量出来的，标定一次不用动
  *   2) 控制参数：调 PID 时改这里
  *   3) 演示参数：考核时想跑多快
  ******************************************************************************
  */
#ifndef __APP_CONFIG_H
#define __APP_CONFIG_H

/* ==========================================================================
 * 1. 机械参数（★ 必须实测，否则速度/距离全不准）
 * ========================================================================== */
#define WHEEL_DIAMETER_MM   65.0f   /* 轮子直径，卡尺量 */
#define GEAR_RATIO          30.0f   /* 减速比，看电机标签（1:30 就填 30）*/
#define ENCODER_PPR         11.0f   /* 编码器单相每转脉冲数（霍尔常见 11 或 13）*/
#define ENCODER_EDGE         4.0f   /* 四倍频：TIM 编码器模式 TI12 天然四倍频 */
#define WHEEL_BASE_MM      168.0f   /* ★ 轮距：实测左右轮【中心】距离 168mm */

/* 输出轴转一圈的计数 = 11 × 4 × 30 = 1320 */
#define ENCODER_CPR   (ENCODER_PPR * ENCODER_EDGE * GEAR_RATIO)

/* ==========================================================================
 * 2. 方向修正（装反了只改这里，别动算法）
 *    改法：给正占空比，看车往哪走；看计数是正还是负
 * ========================================================================== */
#define MOTOR_L_SIGN   (+1)   /* 左电机：正占空比是否让车前进 */
#define MOTOR_R_SIGN   (+1)   /* 右电机：同上 */
#define ENC_L_SIGN     (-1)   /* 左编码器：实测计数与电机反向，取 -1 */
#define ENC_R_SIGN     (+1)   /* 右编码器：实测计数方向与左轮相反，取 +1 */

/* ==========================================================================
 * 3. PWM 与电机
 *    TIM3: PSC=0, ARR=3599 → 72MHz/3600 = 20kHz（超出人耳，电机最安静）
 * ========================================================================== */
#define PWM_ARR         3599    /* 满占空比对应的 CCR 值 */
#define PWM_DEADZONE     280    /* ★ 死区：从 0 慢慢加，轮子刚转时的值，必须实测 */
#define PWM_STOP_BAND     40    /* PID 输出小于此值直接关断，防止静止蠕动 */

/* ==========================================================================
 * 4. 控制周期
 * ========================================================================== */
#define CTRL_DT_S       0.01f   /* 速度环 100Hz = 10ms */
#define CTRL_PERIOD_MS    10

/* ==========================================================================
 * 5. 速度反馈滤波
 * ========================================================================== */
#define SPD_LPF_ALPHA   0.6f    /* 一阶低通：越小越平滑越滞后（0.4~0.8）*/
#define SPEED_MAX_MM_S  900.0f  /* 目标速度限幅 */

/* ==========================================================================
 * 6. 速度环 PID（增量式）
 *    单位：误差 mm/s → 输出 CCR（0~3599）
 *    调参顺序：先 Kp，再 Ki，最后视抖动加一点 Kd
 * ========================================================================== */
#define PID_L_KP         3.0f
#define PID_L_KI        25.0f
#define PID_L_KD         0.0f
#define PID_R_KP         3.0f
#define PID_R_KI        25.0f
#define PID_R_KD         0.0f

/* ==========================================================================
 * 7. 演示模式
 *    0 = 恒速（看稳态误差和抖动）
 *    1 = 阶跃（0 → 目标，看响应时间；★ 答辩画曲线用这个）
 *    2 = 方波（目标来回跳，看跟踪能力）
 * ========================================================================== */
#define DEMO_MODE          3
#define DEMO_SPEED_MM_S  700.0f
#define DEMO_STEP_HOLD_S   3.0f   /* 阶跃模式：跑几秒换下一档 */

/* ==========================================================================
 * 10. 定位与航向（40 分项）
 * ========================================================================== */
#define ODO_DT_S        0.02f      /* 里程计周期 20ms = 50Hz */
#define ODO_PERIOD_MS     20
#define COMP_ALPHA      0.98f      /* 互补滤波：陀螺仪权重，0.95~0.99 */
#define DEG2RAD         0.01745329f

#define HEADING_KP       2.0f      /* 直行时航向保持的 P 增益（rad误差→rad/s）*/
#define HEADING_W_MAX    3.0f      /* 航向修正角速度限幅 */
#define TURN_KP          4.0f      /* 原地转向的 P 增益 */
#define TURN_W_MAX       4.0f
#define TURN_TOL_RAD    0.0175f    /* 1° 到位容差 */

/* --- MPU6050 --- */
#define GYRO_LSB_PER_DPS    65.5f  /* ±500dps 量程：65.5 LSB/(°/s) */
#define GYRO_CALIB_N        1000   /* 上电静止标定采样数（约 1 秒）*/
#define GYRO_Z_SIGN         (-1)   /* 模块翻面安装 → Z 轴反向，取 -1；正面装取 +1 */

#define MISSION_SPEED_MM_S  300.0f /* 任务模式下的直行速度 */
#define MISSION_SIDE_MM     400.0f /* 正方形边长 */

/* --- 定点导航（二维定位演示）--- */
#define GOTO_SPEED_MM_S     250.0f /* 导航时的直行速度 */
#define GOTO_TOL_MM          25.0f /* 到点判定半径 */
#define GOTO_SLOW_MM        150.0f /* 离目标多近开始减速 */
#define SQUARE_THEN_GOTO        1  /* 1 = 跑完方形自动导航回原点 */

#endif /* __APP_CONFIG_H */
